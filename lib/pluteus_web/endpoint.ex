defmodule PluteusWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :pluteus

  alias Pluteus.Design.Faces

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_pluteus_key",
    signing_salt: "+frTnZP5",
    same_site: "Lax"
  ]

  # The socket's only identity is the proxy's headers, as spec-07 §5.2 has it for the
  # client socket. `PluteusWeb.EntityLive` establishes the principal from them again and
  # raises where they name someone other than the page's.
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:x_headers, session: @session_options]],
    longpoll: [connect_info: [:x_headers, session: @session_options]]

  # spec-07 §5.2. Only the `x-` headers reach a socket, which is where the
  # proxy's secret and identity travel.
  socket "/socket", PluteusWeb.ClientSocket,
    websocket: [connect_info: [:x_headers]],
    longpoll: false

  # The vendored faces, from where the vendor task writes them rather than from a copy
  # under priv/static. One set of bytes, beside the licences that must travel with them.
  plug Plug.Static,
    at: "/fonts",
    from: {:pluteus, "priv/fonts"},
    gzip: false,
    only: Faces.files()

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :pluteus,
    gzip: not code_reloading?,
    only: PluteusWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :pluteus
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    body_reader: {PluteusWeb.RawFormBody, :read_body, []},
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug PluteusWeb.Router
end
